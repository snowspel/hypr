#!/bin/bash
# Window look (gaps, border, rounding, shadow, blur, animations).
# Each look is a small JSON file in ~/.config/snow/looks/. This script turns it into ~/.config/hypr/look.lua.
#   look.sh set <name>          use this look and reload Hyprland
#   look.sh save <name> <json> [old]  save a look (from the Themes menu editor) and use it; with [old] (a different name) it renames
#   look.sh get <name>          print the look's JSON
#   look.sh --restore           rebuild look.lua from the saved look (no reload)
#   look.sh list | state
D="$HOME/.config/snow"
OUT="$HOME/.config/hypr/look.lua"
cur=$(cat "$D/look" 2>/dev/null); cur=${cur:-minimal}

gen() {   # gen <json file>  -> Lua on stdout
  jq -r --arg name "$(basename "$1" .json)" '
  def r: (. * 100 | round) / 100;
  . as $p
  | ($p.anim_curve == "spring") as $sp
  | (if $sp then "quick" else $p.anim_curve end) as $oc
  | def a($leaf; $speed; $style): (if $sp then "spr" else "anim" end) + "(\"" + $leaf + "\", " + ($speed | r | tostring) + ", \"" + (if $sp then "easy" else $p.anim_curve end) + "\"" + (if $style != "" then ", \"" + $style + "\"" else "" end) + ")";
  def o($leaf; $speed; $style): "anim(\"" + $leaf + "\", " + ($speed | r | tostring) + ", \"" + $oc + "\"" + (if $style != "" then ", \"" + $style + "\"" else "" end) + ")";
  [
  "-- snow look: " + $name + "  (generated by look.sh from looks/" + $name + ".json - edit it from the Themes menu)",
  "local home   = os.getenv(\"HOME\")",
  "local okc, colors = pcall(dofile, home .. \"/.config/hypr/theme-colors.lua\")",
  "if not okc then colors = require(\"theme-colors\") end",
  "if type(colors) ~= \"table\" then colors = {} end",
  "local function validc(c) return type(c) == \"string\" and c:match(\"^rgba%(%x%x%x%x%x%x%x?%x?%)$\") ~= nil end",
  "if not validc(colors.active1)  then colors.active1  = \"rgba(6366f1ee)\" end",
  "if not validc(colors.active2)  then colors.active2  = \"rgba(999bf5ee)\" end",
  "if not validc(colors.inactive) then colors.inactive = \"rgba(2a2b3caa)\" end",
  "local glow   = colors.glow or \"rgba(00000066)\"",
  "",
  "local function anim(leaf, speed, curve, style)",
  "    hl.animation({ leaf = leaf, enabled = true, speed = speed, bezier = curve, style = style })",
  "end",
  "local function spr(leaf, speed, curve, style)",
  "    hl.animation({ leaf = leaf, enabled = true, speed = speed, spring = curve, style = style })",
  "end",
  "hl.curve(\"easeOutQuint\", { type = \"bezier\", points = { {0.23, 1}, {0.32, 1} } })",
  "hl.curve(\"easeInOutCubic\", { type = \"bezier\", points = { {0.65, 0.05}, {0.36, 1} } })",
  "hl.curve(\"quick\", { type = \"bezier\", points = { {0.15, 0}, {0.1, 1} } })",
  "hl.curve(\"linear\", { type = \"bezier\", points = { {0, 0}, {1, 1} } })",
  "hl.curve(\"easy\", { type = \"spring\", mass = 1, stiffness = 238.1191, dampening = 24.21279333 })",
  "",
  "hl.config({",
  "    general = {",
  "        gaps_in = \($p.gaps_in), gaps_out = \($p.gaps_out), border_size = \($p.border_size),",
  "        col = { active_border = { colors = { colors.active1, colors.active2 }, angle = 45 }, inactive_border = colors.inactive },",
  "    },",
  "    decoration = {",
  "        rounding = \($p.rounding), rounding_power = \($p.rounding_power),",
  "        active_opacity = \(($p.active_opacity // 1) | r), inactive_opacity = \($p.inactive_opacity | r),",
  "        shadow = { enabled = \($p.shadow), range = \($p.shadow_range), render_power = \($p.shadow_power), color = " + (if $p.shadow_glow then "glow" else "0xaa000000" end) + " },",
  "        blur = { enabled = \($p.blur), size = \($p.blur_size), passes = \($p.blur_passes), noise = \($p.blur_noise | r), vibrancy = \($p.blur_vibrancy | r), popups = true },",
  "    },",
  "    animations = { enabled = \($p.anim) },",
  "})"
  ]
  + (if $p.anim then [
      a("windows"; $p.anim_speed; "popin \($p.anim_popin)%"),
      a("windowsOut"; $p.anim_speed * 0.6; "popin \($p.anim_popin)%"),
      o("fade"; $p.anim_speed * 0.7; ""),
      o("layersIn"; $p.anim_speed * 0.8; "popin \([$p.anim_popin + 5, 100] | min)%"),
      o("layersOut"; $p.anim_speed * 0.6; "fade"),
      o("workspaces"; $p.anim_speed; $p.anim_workspace),
      o("border"; $p.anim_speed * 1.2; ""),
      o("global"; $p.anim_speed * 1.2; "")
    ] else [] end)
  + (if $p.panel_blur then [
      "-- blur behind the snow panels (launcher, Super+Tab, power, themes, clock)",
      "for _, ns in ipairs({ \"snow-launcher\", \"snow-control\", \"snow-power\", \"snow-themes\", \"snow-clock\" }) do",
      "    hl.layer_rule({ name = \"blur-\" .. ns, match = { namespace = \"^\" .. ns .. \"$\" }, blur = true, ignore_alpha = 0.2 })",
      "end"
    ] else [] end)
  + (if $p.terminal_opacity < 1 then [
      "hl.window_rule({ name = \"kitty-glass\", match = { class = \"^kitty$\" }, opacity = \"\($p.terminal_opacity | r)\" })"
    ] else [] end)
  | join("\n")' "$1"
}

case "${1:-state}" in
  list)  for f in "$D"/looks/*.json; do [ -f "$f" ] && basename "$f" .json; done ;;
  state) echo "$cur" ;;
  get)   cat "$D/looks/${2:-$cur}.json" 2>/dev/null ;;
  --restore)
    [ -f "$D/looks/$cur.json" ] && gen "$D/looks/$cur.json" > "$OUT.tmp" && mv "$OUT.tmp" "$OUT" ;;
  save)
    n=$(echo "${2:-}" | tr ' ' '-' | tr -cd 'A-Za-z0-9_-')
    [ -n "$n" ] || { echo "bad look name"; exit 1; }
    echo "${3:-}" | jq -e '.gaps_in != null and .rounding != null and .anim_curve != null' >/dev/null 2>&1 || { echo "bad look data"; exit 1; }
    old=$(echo "${4:-}" | tr -cd 'A-Za-z0-9_-')
    echo "$3" | jq . > "$D/looks/$n.json" || exit 1
    [ -n "$old" ] && [ "$old" != "$n" ] && rm -f "$D/looks/$old.json"      # rename: remove the old file
    exec bash "$0" set "$n" ;;
  set)
    n="${2:-}"; [ -f "$D/looks/$n.json" ] || { echo "look not found: $n"; exit 1; }
    gen "$D/looks/$n.json" > "$OUT.tmp" && mv "$OUT.tmp" "$OUT" || { rm -f "$OUT.tmp"; echo "could not build look"; exit 1; }
    echo "$n" > "$D/look"
    [ -n "$HYPRLAND_INSTANCE_SIGNATURE" ] && hyprctl reload >/dev/null 2>&1
    echo "look: $n" ;;
esac
